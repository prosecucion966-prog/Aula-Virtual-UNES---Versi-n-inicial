-- Esquema inicial de Aula Virtual UNES para Neon PostgreSQL.
-- Ejecutar en una base nueva. No elimina ni modifica tablas existentes.

CREATE TABLE IF NOT EXISTS estudiantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  nombre_completo VARCHAR(200) NOT NULL,
  cedula VARCHAR(40),
  telefono VARCHAR(40),
  profesion VARCHAR(160),
  institucion VARCHAR(200),
  password_hash TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS usuarios_sistema (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  nombre_completo VARCHAR(200) NOT NULL,
  cedula VARCHAR(40),
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL CHECK (rol IN ('supervisor', 'administrador')),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS progreso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
  unidad_id INTEGER NOT NULL CHECK (unidad_id BETWEEN 1 AND 9),
  guia_leida BOOLEAN NOT NULL DEFAULT FALSE,
  test_intentos INTEGER NOT NULL DEFAULT 0 CHECK (test_intentos >= 0),
  test_mejor_nota NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (test_mejor_nota BETWEEN 0 AND 20),
  completar_intentos INTEGER NOT NULL DEFAULT 0 CHECK (completar_intentos >= 0),
  completar_mejor_nota NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (completar_mejor_nota BETWEEN 0 AND 20),
  aprobada BOOLEAN NOT NULL DEFAULT FALSE,
  completado BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (estudiante_id, unidad_id)
);

CREATE INDEX IF NOT EXISTS progreso_estudiante_idx ON progreso(estudiante_id);
CREATE INDEX IF NOT EXISTS usuarios_sistema_rol_activo_idx ON usuarios_sistema(rol, activo);
