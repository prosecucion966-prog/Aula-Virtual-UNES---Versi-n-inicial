-- Aula Virtual UNES · Esquema PostgreSQL para Neon
-- Esquema completo inicial. No elimina tablas ni datos existentes.
-- El backend debe utilizar estos nombres de tablas y columnas.

CREATE TABLE IF NOT EXISTS estudiantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  nombre_completo VARCHAR(200) NOT NULL,
  cedula VARCHAR(40),
  telefono VARCHAR(40),
  profesion VARCHAR(160),
  institucion VARCHAR(200),
  password_hash TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT estudiantes_email_lowercase CHECK (email = lower(email)),
  CONSTRAINT estudiantes_email_format CHECK (position('@' in email) > 1)
);

CREATE TABLE IF NOT EXISTS usuarios_sistema (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  nombre_completo VARCHAR(200) NOT NULL,
  cedula VARCHAR(40),
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL CHECK (rol IN ('supervisor', 'administrador')),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT usuarios_sistema_email_lowercase CHECK (email = lower(email)),
  CONSTRAINT usuarios_sistema_email_format CHECK (position('@' in email) > 1)
);

CREATE TABLE IF NOT EXISTS progreso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
  unidad_id SMALLINT NOT NULL CHECK (unidad_id BETWEEN 1 AND 9),
  guia_leida BOOLEAN NOT NULL DEFAULT FALSE,
  test_intentos INTEGER NOT NULL DEFAULT 0 CHECK (test_intentos >= 0),
  test_mejor_nota NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (test_mejor_nota BETWEEN 0 AND 20),
  completar_intentos INTEGER NOT NULL DEFAULT 0 CHECK (completar_intentos >= 0),
  completar_mejor_nota NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (completar_mejor_nota BETWEEN 0 AND 20),
  aprobada BOOLEAN NOT NULL DEFAULT FALSE,
  completado BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT progreso_estudiante_unidad_unique UNIQUE (estudiante_id, unidad_id)
);

CREATE TABLE IF NOT EXISTS certificados (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE RESTRICT UNIQUE,
  codigo VARCHAR(100) NOT NULL UNIQUE,
  promedio_final NUMERIC(5,2) NOT NULL CHECK (promedio_final BETWEEN 0 AND 20),
  fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS log_actividad (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_sistema_id BIGINT REFERENCES usuarios_sistema(id) ON DELETE SET NULL,
  actividad TEXT NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS estudiantes_activo_created_idx ON estudiantes (activo, created_at DESC);
CREATE INDEX IF NOT EXISTS usuarios_sistema_rol_activo_idx ON usuarios_sistema (rol, activo);
CREATE INDEX IF NOT EXISTS progreso_estudiante_idx ON progreso (estudiante_id);
CREATE INDEX IF NOT EXISTS progreso_aprobada_idx ON progreso (aprobada);
CREATE INDEX IF NOT EXISTS certificados_fecha_idx ON certificados (fecha_emision DESC);
CREATE INDEX IF NOT EXISTS log_actividad_fecha_idx ON log_actividad (fecha DESC);
CREATE INDEX IF NOT EXISTS log_actividad_usuario_fecha_idx ON log_actividad (usuario_sistema_id, fecha DESC);

CREATE OR REPLACE FUNCTION set_progreso_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS progreso_updated_at_trigger ON progreso;
CREATE TRIGGER progreso_updated_at_trigger
BEFORE UPDATE ON progreso
FOR EACH ROW EXECUTE FUNCTION set_progreso_updated_at();
